<h1>Kleine Wolkenhof Chronik</h1>
<div id="chronik">

    <p>Die Geschichte des
        heutigen Anwesens Wolkenhof am S&uuml;dhang des Hofbergs gelegen, l&auml;sst
        sich zur Zeit der römischen Landnahme zur&uuml;ck verfolgen. Im Sp&auml;tmittelalter
        war der Wolkenhof der Sitz der Herren von „Wolkenstein“zz, einem
        murrhardter Kleinadel.
    </p>

    <p>Nat&uuml;rlich ist von
        diesen fr&uuml;hen Spuren nichts mehr zu sehen. Das &auml;lteste Geb&auml;ude ist
        heute das so genannte Sch&auml;ferh&auml;uschen, das 1775 erbaut wurde.
    </p>

    <p>Heinrich von Z&uuml;gel
        kaufte das ganze Wolkenhof-Gel&auml;nde 1873 vom Verkauferlös eines
        Bildes, das bei der Weltausstellung die Goldmedaille erhalten hatte.
    </p>

    <p>Kurze Zeit
        darauf wurde das Sandsteingeb&auml;ude errichtet und im Lauf der Jahre
        mehrfach umgestaltet - in dem sich heute eine Wohnung und der
        Waldorfkindergarten befinden.
    </p>

    <p>Hinter dem
        Haus befindet sich ein kleiner See und gemauerter &uuml;berlauf der Quelle
        am Hoffeld. Er befindet sich hier seit 1893, wurde urspr&uuml;nglich als
        Ententeich angelegt.
    </p>

    <p>1907 wurde das
        Hauptgeb&auml;ude in seiner heutigen Form geschaffen. Z&uuml;gels Idee war es,
        die wachsende Familie im Sommer beisammen zu haben, daher ist dieses Geb&auml;ude
        als Sommerhaus konzipiert und mit einem großen Garten versehen. So gab
        es nur einen beheizten Raum, allerdings von Anfang an eine
        Gasbeleuchtung.
    </p>

    <p>Nach dem Tod
        der Eltern wohnte Z&uuml;gels Schwester Caroline dauerhaft auf dem Wolkenhof
        und betrieb bis zum Jahr 1933 eine Mostsch&auml;nke. Im Jahr 1954 wurde im
        Haupthaus ein richtiges Cafe eingerichtet, das auch Mittagessen anbot.
    </p>

    <p>Im Jahr 1973
        wurde das Sozialwerk der Christengemeinschaft der neue P&auml;chter. Die &uuml;bernachtungen
        und anderen Frei- und Schulaktivit&auml;ten nahmen zu und das Haus stand nun
        G&auml;sten und Sch&uuml;lern &uuml;ber Erdgescho? sowie ersten und zweiten Stock
        zu Verf&uuml;gung.
    </p>

    <p>Nach einer
        Renovierungsphase wurde der Wolkenhof 2007 an die Familie Dietrich
        vermietet. Heute soll die urspr&uuml;ngliche Idee eines Platzes, an dem man sich in
        guter Atmosph&auml;re begegnen und arbeiten kann, wieder aufgenommen sein.
    </p>
</div>